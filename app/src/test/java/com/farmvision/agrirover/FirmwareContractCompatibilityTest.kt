/**
 * Validates cross-platform contract compatibility between the ESP32 C++ firmware
 * implementation (firmware/esp32-main) and the Android domain protocol parser.
 */
class FirmwareContractCompatibilityTest {

    private fun loadFixture(fileName: String): String {
        val stream = javaClass.classLoader?.getResourceAsStream("protocol_fixtures/$fileName")
            ?: javaClass.getResourceAsStream("/protocol_fixtures/$fileName")
            ?: throw IllegalStateException("Fixture not found: protocol_fixtures/$fileName")
        return stream.bufferedReader().use { it.readText() }
    }

    private fun resolveFirmwareFile(relativePath: String): File {
        val f1 = File(relativePath)
        if (f1.exists()) return f1
        val f2 = File("../$relativePath")
        if (f2.exists()) return f2
        return f1
    }

    @Test
    fun verifyFirmwareFilesExist() {
        val platformIoFile = resolveFirmwareFile("firmware/esp32-main/platformio.ini")
        val configFile = resolveFirmwareFile("firmware/esp32-main/include/config.h")
        val safetyHeader = resolveFirmwareFile("firmware/esp32-main/include/safety_core.h")
        val safetySource = resolveFirmwareFile("firmware/esp32-main/src/safety_core.cpp")
        val sensorHeader = resolveFirmwareFile("firmware/esp32-main/include/sensor_manager.h")
        val sensorSource = resolveFirmwareFile("firmware/esp32-main/src/sensor_manager.cpp")
        val webHeader = resolveFirmwareFile("firmware/esp32-main/include/web_server_handler.h")
        val webSource = resolveFirmwareFile("firmware/esp32-main/src/web_server_handler.cpp")
        val mainSource = resolveFirmwareFile("firmware/esp32-main/src/main.cpp")
        val readmeFile = resolveFirmwareFile("firmware/README.md")

        assertTrue("platformio.ini must exist", platformIoFile.exists())
        assertTrue("config.h must exist", configFile.exists())
        assertTrue("safety_core.h must exist", safetyHeader.exists())
        assertTrue("safety_core.cpp must exist", safetySource.exists())
        assertTrue("sensor_manager.h must exist", sensorHeader.exists())
        assertTrue("sensor_manager.cpp must exist", sensorSource.exists())
        assertTrue("web_server_handler.h must exist", webHeader.exists())
        assertTrue("web_server_handler.cpp must exist", webSource.exists())
        assertTrue("main.cpp must exist", mainSource.exists())
        assertTrue("firmware/README.md must exist", readmeFile.exists())
    }

    @Test
    fun verifyCanonicalPinAssignments_MatchHardwareWiringChecklist() {
        val configFile = resolveFirmwareFile("firmware/esp32-main/include/config.h")
        assertTrue("config.h must exist", configFile.exists())
        val content = configFile.readText()

        // Verify ADC1 pins used (avoiding ADC2 Wi-Fi conflict)
        assertTrue(content.contains("#define PIN_SOIL_MOISTURE_1         32"))
        assertTrue(content.contains("#define PIN_SOIL_MOISTURE_2         34"))
        assertTrue(content.contains("#define PIN_SOIL_PH                 35"))

        // Verify Ultrasonic pins
        assertTrue(content.contains("#define PIN_ULTRASONIC_TRIG         13"))
        assertTrue(content.contains("#define PIN_ULTRASONIC_ECHO         14"))

        // Verify Motor Driver pins
        assertTrue(content.contains("#define PIN_MOTOR_PWMA              25"))
        assertTrue(content.contains("#define PIN_MOTOR_AIN1              26"))
        assertTrue(content.contains("#define PIN_MOTOR_AIN2              27"))
        assertTrue(content.contains("#define PIN_MOTOR_PWMB              16"))
        assertTrue(content.contains("#define PIN_MOTOR_BIN1              17"))
        assertTrue(content.contains("#define PIN_MOTOR_BIN2              18"))
        assertTrue(content.contains("#define PIN_MOTOR_STBY              19"))

        // Verify Relay
        assertTrue(content.contains("#define PIN_PUMP_RELAY              5"))
    }

    @Test
    fun verifyFirmwareCapabilitiesEmittedJson_MatchesAndroidDomainModel() {
        // Exact JSON payload format generated by WebServerHandler::handleCapabilities()
        val firmwareCapabilitiesJson = """
        {
          "protocolVersion": "1.0.0",
          "deviceId": "agrirover-main-esp32",
          "firmwareVersion": "v1.0.0-f0-sensors",
          "firmwareStage": "F0",
          "controllerTarget": "Esp32DevKitV1",
          "supportedSensors": [
            {
              "id": "hw-sensor-soil-moisture-probes",
              "type": "SoilMoistureCapacitive",
              "unit": "%",
              "requiresCalibration": true,
              "isAvailable": true
            },
            {
              "id": "hw-sensor-dht22",
              "type": "AtmosphericDht22",
              "unit": "C_RH",
              "requiresCalibration": false,
              "isAvailable": true
            },
            {
              "id": "hw-sensor-soil-ph",
              "type": "AnalogSoilPh",
              "unit": "pH",
              "requiresCalibration": true,
              "isAvailable": true
            },
            {
              "id": "hw-sensor-ultrasonic",
              "type": "DistanceHcSr04",
              "unit": "cm",
              "requiresCalibration": false,
              "isAvailable": true
            }
          ],
          "supportedActuators": [
            {
              "id": "hw-motors-bo-geared",
              "type": "DifferentialDriveMotors",
              "hasPhysicalFeedback": false,
              "isEnabled": false
            },
            {
              "id": "hw-irrigation-pump",
              "type": "SubmersiblePumpRelay",
              "hasPhysicalFeedback": false,
              "isEnabled": false,
              "maxDurationMs": 10000
            }
          ],
          "features": ["TELEMETRY_STREAM", "EMERGENCY_STOP"],
          "isEmergencyStopSupported": true
        }
        """.trimIndent()

        val caps = ProtocolMessageParser.parseCapabilities(firmwareCapabilitiesJson)
        assertEquals(ProtocolConstants.PROTOCOL_VERSION, caps.protocolVersion)
        assertEquals("agrirover-main-esp32", caps.deviceId)
        assertEquals(FirmwareStage.F0, caps.firmwareStage)
        assertEquals("Esp32DevKitV1", caps.controllerTarget)
        assertEquals(4, caps.supportedSensors.size)
        assertEquals(2, caps.supportedActuators.size)

        // Verify all actuators are disabled in F0
        caps.supportedActuators.forEach { actuator ->
            assertFalse("Actuator ${actuator.id} must be disabled in Stage F0", actuator.isEnabled)
            assertFalse("Actuator ${actuator.id} must not claim physical feedback", actuator.hasPhysicalFeedback)
        }

        assertTrue(caps.isEmergencyStopSupported)
        assertTrue(caps.features.contains("TELEMETRY_STREAM"))
        assertTrue(caps.features.contains("EMERGENCY_STOP"))
    }

    @Test
    fun verifyFirmwareTelemetryEmittedJson_MatchesAndroidDomainModel() {
        // Exact JSON payload format generated by WebServerHandler::handleTelemetry()
        val firmwareTelemetryJson = """
        {
          "protocolVersion": "1.0.0",
          "deviceId": "agrirover-main-esp32",
          "firmwareVersion": "v1.0.0-f0-sensors",
          "sequenceNumber": 1042,
          "uptimeMs": 348500,
          "readings": {
            "hw-sensor-soil-moisture-probes": {
              "value": 42.5,
              "rawValue": 2150.0,
              "unit": "%",
              "isValid": true,
              "quality": "OK"
            },
            "hw-sensor-soil-moisture-probe-2": {
              "value": 2200.0,
              "rawValue": 2200.0,
              "unit": "counts",
              "isValid": true,
              "quality": "RAW_UNCALIBRATED"
            },
            "hw-sensor-dht22": {
              "value": 26.8,
              "rawValue": 26.8,
              "unit": "°C",
              "isValid": true,
              "quality": "OK"
            },
            "hw-sensor-soil-ph": {
              "value": 6.8,
              "rawValue": 1820.0,
              "unit": "pH",
              "isValid": true,
              "quality": "OK"
            },
            "hw-sensor-ultrasonic": {
              "value": 45.0,
              "rawValue": 45.0,
              "unit": "cm",
              "isValid": true,
              "quality": "OK"
            }
          },
          "diagnostics": {
            "freeHeapBytes": "142880",
            "wifiRssiDbm": "-54",
            "loopFrequencyHz": "50"
          }
        }
        """.trimIndent()

        val packet = ProtocolMessageParser.parseTelemetry(firmwareTelemetryJson)
        assertEquals("1.0.0", packet.protocolVersion)
        assertEquals(1042L, packet.sequenceNumber)
        assertEquals(348500L, packet.uptimeMs)

        val moisture = packet.readings["hw-sensor-soil-moisture-probes"]
        assertNotNull(moisture)
        assertEquals(42.5, moisture!!.value, 0.001)
        assertEquals("%", moisture.unit)

        val moisture2 = packet.readings["hw-sensor-soil-moisture-probe-2"]
        assertNotNull(moisture2)
        assertEquals(2200.0, moisture2!!.value, 0.001)
        assertEquals(2200.0, moisture2.rawValue, 0.001)
        assertEquals("counts", moisture2.unit)
        assertEquals("RAW_UNCALIBRATED", moisture2.quality)

        val dht = packet.readings["hw-sensor-dht22"]
        assertNotNull(dht)
        assertEquals(26.8, dht!!.value, 0.001)

        val ph = packet.readings["hw-sensor-soil-ph"]
        assertNotNull(ph)
        assertEquals(6.8, ph!!.value, 0.001)

        val ultrasonic = packet.readings["hw-sensor-ultrasonic"]
        assertNotNull(ultrasonic)
        assertEquals(45.0, ultrasonic!!.value, 0.001)

        assertEquals("142880", packet.diagnostics["freeHeapBytes"])
    }

    @Test
    fun verifyFirmwareErrorResponse_MatchesContractErrorCodes() {
        // Test ERR_ACTUATOR_DISABLED generated on actuation attempt in F0
        val actuatorDisabledJson = """
        {
          "protocolVersion": "1.0.0",
          "errorCode": "ERR_ACTUATOR_DISABLED",
          "message": "Actuator commanded while in Stage F0 sensors-only firmware until wiring is confirmed.",
          "recoverable": true,
          "timestampMs": 1700000000000
        }
        """.trimIndent()

        val err1 = ProtocolMessageParser.parseErrorResponse(actuatorDisabledJson)
        assertEquals(ProtocolErrorCode.ERR_ACTUATOR_DISABLED, err1.errorCode)
        assertTrue(err1.recoverable)

        // Test ERR_AUTH_MISSING
        val authMissingJson = """
        {
          "protocolVersion": "1.0.0",
          "errorCode": "ERR_AUTH_MISSING",
          "message": "X-AgriRover-Token header was omitted.",
          "recoverable": true,
          "timestampMs": 1700000000001
        }
        """.trimIndent()

        val err2 = ProtocolMessageParser.parseErrorResponse(authMissingJson)
        assertEquals(ProtocolErrorCode.ERR_AUTH_MISSING, err2.errorCode)

        // Test ERR_EMERGENCY_STOP_ACTIVE
        val estopActiveJson = """
        {
          "protocolVersion": "1.0.0",
          "errorCode": "ERR_EMERGENCY_STOP_ACTIVE",
          "message": "Motion command rejected: Emergency Stop is currently latched active.",
          "recoverable": true,
          "timestampMs": 1700000000002
        }
        """.trimIndent()

        val err3 = ProtocolMessageParser.parseErrorResponse(estopActiveJson)
        assertEquals(ProtocolErrorCode.ERR_EMERGENCY_STOP_ACTIVE, err3.errorCode)
    }

    @Test
    fun verifyFirmwareEmergencyStopAck_MatchesAndroidModel() {
        // E-Stop executes unconditionally without requiring auth token
        val estopAckJson = """
        {
          "protocolVersion": "1.0.0",
          "cmdId": "estop-unconditional",
          "status": "ACCEPTED",
          "reasonCode": "ESTOP_ENGAGED",
          "latencyMs": 1,
          "timestampMs": 1700000000012
        }
        """.trimIndent()

        val ack = ProtocolMessageParser.parseAcknowledgement(estopAckJson)
        assertEquals("estop-unconditional", ack.cmdId)
        assertEquals(CommandAckStatus.ACCEPTED, ack.status)
        assertEquals("ESTOP_ENGAGED", ack.reasonCode)
        assertEquals(1L, ack.latencyMs)
        assertTrue(ack.isAccepted)
    }

    @Test
    fun verifyFirmwareEmergencyStopResetAck_MatchesAndroidModel() {
        // E-Stop Reset requires valid authentication and returns deliberate re-arm ACK
        val resetAckJson = """
        {
          "protocolVersion": "1.0.0",
          "cmdId": "estop-reset",
          "status": "ACCEPTED",
          "reasonCode": "ESTOP_RESET",
          "latencyMs": 2,
          "timestampMs": 1700000000020
        }
        """.trimIndent()

        val ack = ProtocolMessageParser.parseAcknowledgement(resetAckJson)
        assertEquals("estop-reset", ack.cmdId)
        assertEquals(CommandAckStatus.ACCEPTED, ack.status)
        assertEquals("ESTOP_RESET", ack.reasonCode)
        assertEquals(2L, ack.latencyMs)
        assertTrue(ack.isAccepted)
    }
}
